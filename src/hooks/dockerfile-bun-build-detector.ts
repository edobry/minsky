/**
 * Generator/resolver for the `RUN bun build ...` invocation line in the
 * root `Dockerfile` (mt#3091).
 *
 * Sibling to `src/hooks/workspace-copy-detector.ts` (mt#2621) — same
 * marker-delimited-block + pre-commit-auto-regen-and-restage PATTERN, but
 * a deliberately separate module rather than an extension of that one.
 * `workspace-copy-detector.ts`'s discovery criterion (every Dockerfile that
 * runs `bun install --frozen-lockfile`, driven by root package.json's
 * `workspaces` glob) and this module's (the single root `Dockerfile`'s
 * `bun build` line, driven by `scripts/cli-entry.ts`'s canonical
 * `bunBuildArgs()`) are unrelated concerns with different data sources and
 * different scopes (multi-Dockerfile glob-driven vs. single-file
 * fixed-target) — folding them into one file would blur single
 * responsibility for no shared logic beyond "marker-delimited block in a
 * Dockerfile." See `scripts/generate-dockerfile-bun-build.ts` for the
 * script that drives this at commit time, and mt#3091's PR body for the
 * fuller "did we extend mt#2621 directly" evaluation.
 *
 * Unlike `workspace-copy-detector.ts`, this module does not read the
 * canonical command itself — it takes the rendered command STRING as a
 * parameter. That keeps this module a pure function of (Dockerfile text,
 * command string), independently testable, and avoids `src/hooks/*`
 * importing from `scripts/*` (the established import direction in this
 * repo is scripts → src, e.g. `scripts/generate-dockerfile-workspace-copies.ts`
 * importing `src/hooks/workspace-copy-detector.ts`).
 */

/**
 * Marker lines delimiting the generated `bun build` invocation inside the
 * root Dockerfile. Everything between these two lines (exclusive) is
 * mechanically owned by the generator — hand edits inside the block are
 * overwritten on the next regeneration.
 */
export const BUN_BUILD_BLOCK_START = "# === BEGIN GENERATED: bun build invocation (mt#3091) ===";
export const BUN_BUILD_BLOCK_END = "# === END GENERATED: bun build invocation ===";

/**
 * Render the generated bun-build block body (markers + explanatory
 * comment + the `RUN <command>` line). Pure function of the rendered
 * command string.
 */
export function renderBunBuildBlock(command: string): string {
  return [
    BUN_BUILD_BLOCK_START,
    "# Generated by `bun run generate:dockerfile-bun-build`",
    "# (scripts/generate-dockerfile-bun-build.ts) from the canonical",
    "# `bunBuildArgs()` in scripts/cli-entry.ts (the same source",
    "# package.json's `build` script is checked against). Do not hand-edit",
    "# the RUN line below — change bunBuildArgs() and rerun the generator;",
    "# pre-commit does this automatically and re-stages the result (mt#3091,",
    "# mirroring the mt#2621 workspace-COPY-block pattern).",
    `RUN ${command}`,
    BUN_BUILD_BLOCK_END,
  ].join("\n");
}

export interface ApplyBunBuildBlockResult {
  /** Full Dockerfile text with the generated block substituted in. */
  text: string;
  /** True iff `text` differs from the input `dockerfileText`. */
  changed: boolean;
}

export interface ApplyBunBuildBlockError {
  /**
   * Human-readable diagnostic naming the missing marker(s). The caller
   * (script / pre-commit step) surfaces this verbatim and fails loudly —
   * a Dockerfile that doesn't carry the markers can't be safely
   * auto-generated into.
   */
  error: string;
}

function escapeRegExpLiteral(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Matches every `BUN_BUILD_BLOCK_START ... BUN_BUILD_BLOCK_END` span
 * (non-greedy, so adjacent blocks aren't swallowed into one match; `g`
 * flag, so `.replace()` below rewrites EVERY occurrence, not just the
 * first). Mirrors `workspace-copy-detector.ts`'s `BLOCK_SPAN_RE` — this
 * repo currently only wraps the block around the root Dockerfile's single
 * `bun build` line, but a non-global regex would silently leave a SECOND
 * occurrence stale if this pattern is ever reused for a multi-stage
 * Dockerfile (the sibling module's own docstring names
 * `services/cockpit/Dockerfile`'s builder+runtime stages as exactly that
 * case). Caught by reviewer-bot mt#3091 PR #2305 R1 BLOCKING.
 */
const BLOCK_SPAN_RE = new RegExp(
  `${escapeRegExpLiteral(BUN_BUILD_BLOCK_START)}[\\s\\S]*?${escapeRegExpLiteral(BUN_BUILD_BLOCK_END)}`,
  "g"
);

/**
 * Replace every `BUN_BUILD_BLOCK_START`/`BUN_BUILD_BLOCK_END` span in
 * `dockerfileText` with the freshly rendered block for `command`.
 *
 * Returns `{ error }` when no complete marker span is found at all — the
 * Dockerfile hasn't adopted the generated-block convention (a one-time
 * setup gap, not staleness).
 */
export function applyGeneratedBunBuildBlock(
  dockerfileText: string,
  command: string
): ApplyBunBuildBlockResult | ApplyBunBuildBlockError {
  if (!BLOCK_SPAN_RE.test(dockerfileText)) {
    return {
      error:
        `missing the generated bun-build markers ` +
        `("${BUN_BUILD_BLOCK_START}" / "${BUN_BUILD_BLOCK_END}"). ` +
        `Add the block once (see Dockerfile for the expected shape), then rerun the generator.`,
    };
  }
  const newBlock = renderBunBuildBlock(command);
  // `BLOCK_SPAN_RE` carries the `g` flag and is therefore stateful
  // (`.test()` above advanced `lastIndex`) — reset before `.replace()`.
  BLOCK_SPAN_RE.lastIndex = 0;
  const newText = dockerfileText.replace(BLOCK_SPAN_RE, () => newBlock);
  return { text: newText, changed: newText !== dockerfileText };
}
