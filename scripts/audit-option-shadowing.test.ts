/**
 * Pins the parent/child option-shadowing set (mt#4076).
 *
 * The sweep itself is a one-time answer; this is the standing guard. A NEW
 * collision — a subcommand declaring an option name an ancestor also declares —
 * fails here, at authoring time, instead of reaching an operator as a flag that
 * parses, prints in `--help`, and silently does nothing.
 *
 * That failure mode is why the guard is worth its weight: the same defect was
 * arrived at twice independently before it was fixed (mt#3830 from the public
 * quick-start path, mt#3816 during implementation), because nothing detects it.
 *
 * **What this reads, and the bound that puts on it.** The assertions below run
 * against the COMMITTED `src/generated/completion-manifest.json`, not against a
 * tree rebuilt from source at test time. So the guard fires when a new collision
 * reaches the committed manifest — not at the instant someone adds a colliding
 * `.option()` call. In practice those are the same moment: the manifest is
 * regenerated by `bun run build` and by the pre-commit hook (which restages it),
 * so a new option lands in the same commit as its manifest entry. If that
 * regeneration ever stops being automatic, this guard silently weakens to
 * "nothing NEW has been committed since the manifest was last built" — which is
 * why the second test below also fails on a DISAPPEARED collision, catching a
 * manifest that has drifted out of step in either direction.
 */

import { describe, test, expect } from "bun:test";
import { findShadowedOptions, type ManifestNode } from "./audit-option-shadowing";
import manifest from "../src/generated/completion-manifest.json";

/**
 * Every collision known to exist, each handled by reading the merged view.
 *
 * Adding a row here is a deliberate act: it asserts the subcommand's action
 * calls `mergedSetupOpts` (or commander's `optsWithGlobals()` directly).
 * Without that, the row records a live defect rather than a handled one —
 * `src/commands/setup/index.test.ts` is what proves the handling.
 */
const KNOWN_AND_HANDLED: ReadonlyArray<{ command: string; flag: string }> = [
  { command: "minsky setup github-app", flag: "--repo" },
  { command: "minsky setup db", flag: "--connection-string" },
  { command: "minsky setup db", flag: "--yes" },
  { command: "minsky setup local-http", flag: "--repo" },
];

function key(hit: { command: string; flag: string }): string {
  return `${hit.command} ${hit.flag}`;
}

describe("parent/child option shadowing across the whole CLI", () => {
  test("no collision exists that is not known and handled", () => {
    const found = findShadowedOptions(manifest as ManifestNode)
      .map(key)
      .sort();
    const known = KNOWN_AND_HANDLED.map(key).sort();

    // Reported as a set difference rather than a bare inequality: on failure the
    // message names the offending command and flag, which is the whole question.
    const unexpected = found.filter((f) => !known.includes(f));
    expect(unexpected).toEqual([]);
  });

  test("every known collision is still present — a stale entry is also a finding", () => {
    // If a collision disappears (someone renamed the parent's option, say), the
    // corresponding merge became dead code. That should be noticed, not left to
    // rot as a comment claiming a hazard that no longer exists.
    const found = findShadowedOptions(manifest as ManifestNode)
      .map(key)
      .sort();
    const known = KNOWN_AND_HANDLED.map(key).sort();

    const missing = known.filter((k) => !found.includes(k));
    expect(missing).toEqual([]);
  });
});

describe("findShadowedOptions", () => {
  test("reports the OUTERMOST declarer, which is the one commander binds to", () => {
    const tree: ManifestNode = {
      name: "root",
      options: [{ flags: ["--repo"] }],
      subcommands: [
        {
          name: "mid",
          options: [{ flags: ["--repo"] }],
          subcommands: [{ name: "leaf", options: [{ flags: ["--repo"] }] }],
        },
      ],
    };

    const hits = findShadowedOptions(tree);

    expect(hits).toEqual([
      { command: "root mid", flag: "--repo", declaredBy: "root" },
      { command: "root mid leaf", flag: "--repo", declaredBy: "root" },
    ]);
  });

  test("a name declared only on a child is not a collision", () => {
    const tree: ManifestNode = {
      name: "root",
      options: [{ flags: ["--repo"] }],
      subcommands: [{ name: "child", options: [{ flags: ["--via"] }] }],
    };
    expect(findShadowedOptions(tree)).toEqual([]);
  });

  test("short flags are ignored — they collide on different rules", () => {
    const tree: ManifestNode = {
      name: "root",
      options: [{ flags: ["-p", "--port"] }],
      subcommands: [{ name: "child", options: [{ flags: ["-p", "--pretty"] }] }],
    };
    expect(findShadowedOptions(tree)).toEqual([]);
  });

  test("a tree with no options at all is handled", () => {
    expect(findShadowedOptions({ name: "root" })).toEqual([]);
  });
});
