/**
 * Shared hook-copy compile target (mt#3854)
 *
 * Both `claude-hooks` and `codex-hooks` do the same thing: read every hook
 * source from `.minsky/hooks/*.ts` and emit it under a harness directory with a
 * shebang, a generation banner, and a provenance comment, marked executable.
 * The ONLY difference is the output directory.
 *
 * This module holds that machinery once so the two targets cannot drift apart.
 * That is not a style preference here — mt#3854 exists BECAUSE a hand-made copy
 * of the harness config drifted 75 guards behind its source, and implementing
 * the fix by duplicating a 214-line target would reproduce the same failure one
 * level up, in code that is harder to notice going stale than a directory is.
 *
 * Extracted from `claude-hooks.ts` (mt#2304), whose behaviour is preserved
 * exactly — including its public constants, which that module re-exports so its
 * tests and any external importer are unaffected.
 *
 * @see mt#3854 — the codex target that motivated the extraction
 * @see mt#2280 / ADR-016 — compile pipeline convergence (one pipeline, all targets)
 * @see .claude/hooks/check-generated-file-edit.ts — banner recognition
 */

import { join, basename } from "path";
import realFs from "fs/promises";
import type {
  MinskyCompileTarget,
  MinskyCompileResult,
  MinskyTargetOptions,
  MinskyCompileFsDeps,
} from "../types";

// ---------------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------------

export const HOOK_SHEBANG = "#!/usr/bin/env bun";
export const HOOK_COMPILE_BANNER = "// Generated by minsky compile. Do not edit directly.";
export const HOOK_FILE_MODE = 0o755;

/**
 * Source directory where hooks are authored — the same for every harness.
 * Pattern: `.minsky/hooks/<name>.ts`
 */
export function hookSourceDir(workspacePath: string): string {
  return join(workspacePath, ".minsky", "hooks");
}

// ---------------------------------------------------------------------------
// Content builder
// ---------------------------------------------------------------------------

/**
 * Build the compiled content for a hook source file.
 *
 * The banner header is always:
 *   #!/usr/bin/env bun
 *   // Generated by minsky compile. Do not edit directly.
 *   // Source: .minsky/hooks/<name>.ts
 *
 * If the source already has a `#!/usr/bin/env bun` shebang on line 1, it is
 * stripped before building (we always add it fresh so the output is
 * deterministic regardless of whether the source has one).
 *
 * The provenance line names the SOURCE, not the output, so it is identical
 * across harnesses — which is what makes one builder correct for all of them.
 */
export function buildHookContent(sourceContent: string, hookFileName: string): string {
  const strippedContent = sourceContent.startsWith(`${HOOK_SHEBANG}\n`)
    ? sourceContent.slice(`${HOOK_SHEBANG}\n`.length)
    : sourceContent;

  const provenance = `// Source: .minsky/hooks/${hookFileName}`;

  return `${HOOK_SHEBANG}\n${HOOK_COMPILE_BANNER}\n${provenance}\n\n${strippedContent}`;
}

// ---------------------------------------------------------------------------
// Source discovery
// ---------------------------------------------------------------------------

/**
 * List `*.ts` source filenames under `.minsky/hooks/` (excluding `*.test.ts`).
 * Returns only the bare filename (e.g. `substrate-bypass-detector.ts`).
 */
export async function discoverHookSourceFiles(
  workspacePath: string,
  fs: MinskyCompileFsDeps
): Promise<string[]> {
  const sourceDir = hookSourceDir(workspacePath);
  let entries: string[];
  try {
    entries = await fs.readdir(sourceDir);
  } catch {
    return [];
  }

  return entries.filter(
    (name) =>
      name.endsWith(".ts") &&
      !name.endsWith(".test.ts") &&
      // Skip non-TS files (e.g. .md reference docs, SPEC.md)
      !name.endsWith(".md")
  );
}

// ---------------------------------------------------------------------------
// Target factory
// ---------------------------------------------------------------------------

export interface HookCopyTargetConfig {
  /** Machine identifier, e.g. `"claude-hooks"`. */
  id: string;
  /** Human-readable display name, e.g. `"Claude Hooks"`. */
  displayName: string;
  /**
   * Path segments below the workspace root for the output directory, e.g.
   * `[".claude", "hooks"]`. Given as segments rather than a joined string so
   * callers cannot accidentally pass a platform-specific separator.
   */
  outputDirSegments: readonly string[];
}

/**
 * Build a hook-copy target for one harness.
 *
 * `sharedOutputDirectory` is always false: a harness hooks directory is owned
 * exclusively by this target once the harness is wired up, so `--check` should
 * report orphans there rather than tolerate them. That is what makes a stale
 * leftover a build failure instead of a silent fossil.
 */
export function makeHookCopyTarget(config: HookCopyTargetConfig): MinskyCompileTarget {
  const outputDir = (workspacePath: string): string =>
    join(workspacePath, ...config.outputDirSegments);
  const outputPath = (workspacePath: string, hookFileName: string): string =>
    join(outputDir(workspacePath), hookFileName);

  return {
    id: config.id,
    displayName: config.displayName,
    sharedOutputDirectory: false,

    defaultOutputPath(workspacePath: string): string {
      return outputDir(workspacePath);
    },

    async listOutputFiles(
      _options: MinskyTargetOptions,
      workspacePath: string,
      fsDeps?: MinskyCompileFsDeps
    ): Promise<string[]> {
      const fs = fsDeps ?? (realFs as MinskyCompileFsDeps);
      const fileNames = await discoverHookSourceFiles(workspacePath, fs);
      return fileNames.map((name) => outputPath(workspacePath, name));
    },

    async compile(
      options: MinskyTargetOptions,
      workspacePath: string,
      fsDeps?: MinskyCompileFsDeps
    ): Promise<MinskyCompileResult> {
      const fs = fsDeps ?? (realFs as MinskyCompileFsDeps);
      const fileNames = await discoverHookSourceFiles(workspacePath, fs);

      const filesWritten: string[] = [];
      const definitionsIncluded: string[] = [];
      const definitionsSkipped: string[] = [];
      const contentsByPath = new Map<string, string>();
      const dryRunParts: string[] = [];

      for (const fileName of fileNames) {
        const sourcePath = join(hookSourceDir(workspacePath), fileName);

        let sourceContent: string;
        try {
          sourceContent = await fs.readFile(sourcePath, "utf-8");
        } catch (error) {
          const reason = error instanceof Error ? error.message : String(error);
          // Do not swallow silently — surface the error so operators know the
          // source was skipped. Mirrors the claude-skills pattern (mt#2182).
          definitionsSkipped.push(fileName);
          // Log to stderr only; we don't have access to the logger here to
          // avoid a circular dependency — callers can enable debug logging.
          process.stderr.write(
            `[compile:${config.id}] skipping "${fileName}": failed to read ${sourcePath}: ${reason}\n`
          );
          continue;
        }

        const target = outputPath(workspacePath, fileName);
        const content = buildHookContent(sourceContent, basename(sourcePath));

        if (options.dryRun) {
          contentsByPath.set(target, content);
          dryRunParts.push(`// ${target}\n${content}`);
        } else {
          await fs.mkdir(outputDir(workspacePath), { recursive: true });
          await fs.writeFile(target, content, "utf-8");
          // Make the compiled hook executable (0o755) so the harness and bun
          // can run it directly. The Write tool sets 0o644 by default; without
          // chmod the hook silently fails to execute.
          await fs.chmod(target, HOOK_FILE_MODE);
        }

        filesWritten.push(target);
        definitionsIncluded.push(fileName);
      }

      return {
        target: config.id,
        filesWritten,
        definitionsIncluded,
        definitionsSkipped,
        content: options.dryRun ? dryRunParts.join("\n\n") : undefined,
        contentsByPath: options.dryRun ? contentsByPath : undefined,
      };
    },
  };
}
